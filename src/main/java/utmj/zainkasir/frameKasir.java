    private void resetForm() {

        transaksi.resetTransaksi();

        txtNama.setText("");
        txtHarga.setText("");
        txtJumlah.setText("");
        txtTotal.setText("");
        txtBayar.setText("");
        txtKembali.setText("");

        sudahDibayar = false;

        txtNama.requestFocus();
    }
    
    
    private void hitungTotal() {
        try {
            int harga = Integer.parseInt(txtHarga.getText());
            int jumlah = Integer.parseInt(txtJumlah.getText());
            String namaBarang = txtNama.getText();
            
            if (harga <= 0 || jumlah <= 0) {
                JOptionPane.showMessageDialog(this, 
                        "Harga dan jumlah harus lebih dari 0!", 
                        "Peringatan", 
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            if (namaBarang.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                        "Kolom Nama Barang ini wajib diisi ya mas!", 
                        "Peringatan", 
                        JOptionPane.WARNING_MESSAGE);
                return;
            } 
            int total = (harga * jumlah);
            txtTotal.setText(String.valueOf(total));
            
        } catch(NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, 
                    "Harga dan jumlah harus berupa angka ya!", 
                    "Peringatan", 
                    JOptionPane.WARNING_MESSAGE);
        }
    }

    
    private void Bayar() {

        try {

            if (txtNama.getText().trim().isEmpty()
                    || txtHarga.getText().trim().isEmpty()
                    || txtJumlah.getText().trim().isEmpty()
                    || txtBayar.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Semua kolom harus diisi!",
                        "Peringatan",
                        JOptionPane.WARNING_MESSAGE);

                return;
            }

            if (sudahDibayar) {
                JOptionPane.showMessageDialog(
                        this,
                        "Transaksi ini sudah dibayar. "
                        + "Silakan mulai transaksi baru.");
                return;
            }

            int harga = Integer.parseInt(txtHarga.getText());
            int jumlah = Integer.parseInt(txtJumlah.getText());
            int bayar = Integer.parseInt(txtBayar.getText());

            if (harga <= 0 || jumlah <= 0 || bayar < 0) {
                JOptionPane.showMessageDialog(
                        this,
                        "Masukkan angka yang valid!");
                return;
            }

            int total = harga * jumlah;

            if (bayar < total) {

                JOptionPane.showMessageDialog(
                        this,
                        "Uang pembayaran kurang!\n"
                        + "Total: Rp " + total + "\n"
                        + "Dibayar: Rp " + bayar + "\n"
                        + "Kekurangan: Rp " + (total - bayar),
                        "Pembayaran Gagal",
                        JOptionPane.WARNING_MESSAGE);

                return;
            }

            int kembali = bayar - total;

            txtTotal.setText(String.valueOf(total));
            txtKembali.setText(String.valueOf(kembali));

            // Menyimpan transaksi ke dalam riwayat
            String data = "Barang: " + txtNama.getText()
                        + "\nHarga: Rp " + harga
                        + "\nJumlah: " + jumlah
                        + "\nTotal: Rp " + total
                        + "\nBayar: Rp " + bayar
                        + "\nKembalian: Rp " + kembali;

            riwayatTransaksi.add(data);

            sudahDibayar = true;

            JOptionPane.showMessageDialog(
                    this,
                    "Pembayaran berhasil!\n"
                    + "Total: Rp " + total + "\n"
                    + "Kembalian: Rp " + kembali,
                    "Pembayaran Berhasil",
                    JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Harga, jumlah, dan uang bayar harus berupa angka!",
                    "Kesalahan Input",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
